import { fileURLToPath } from 'node:url';

import * as fs from 'fs';
import * as path from 'path';
import { describe, expect,it } from 'vitest';

import {
  CardsPlayedEventSchema,
  PlayerJoinedEventSchema,
  PlayerStatusChangedEventSchema,
  RoomStateSnapshotSchema,
  RoundStartedEventSchema,
  TraceCalledEventSchema,
  TraceResolutionSchema,
  TurnStartedEventSchema,
  VoltageOverloadedEventSchema,
} from './gameEvents';

function findFixturesDir(): string {
  let current = path.dirname(fileURLToPath(import.meta.url));
  while (current && current !== path.parse(current).root) {
    const candidate = path.join(current, 'tests', 'contracts', 'signalr');
    if (fs.existsSync(candidate)) {
      return candidate;
    }
    current = path.dirname(current);
  }
  return path.resolve(process.cwd(), '../../tests/contracts/signalr');
}

const FIXTURES_DIR = findFixturesDir();

describe('SignalR Contract Validation (ADR 0004 & ADR 0007)', () => {
  it('parses TraceCalled fixture generated by backend', () => {
    const raw: unknown = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'TraceCalled.json'), 'utf-8')
    ) as unknown;
    const result = TraceCalledEventSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.type).toBe('TraceCalled');
      expect(result.data.bluffDetected).toBe(true);
      expect(result.data.revealedCards).toHaveLength(1);
      expect(result.data.revealedCards[0].suit).toBe('overload');
    }
  });

  it('parses TurnStarted fixture generated by backend', () => {
    const raw: unknown = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'TurnStarted.json'), 'utf-8')
    ) as unknown;
    const result = TurnStartedEventSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.type).toBe('TurnStarted');
      expect(result.data.currentVoltage).toBe(120);
    }
  });

  it('parses VoltageOverloaded fixture generated by backend', () => {
    const raw: unknown = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'VoltageOverloaded.json'), 'utf-8')
    ) as unknown;
    const result = VoltageOverloadedEventSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.type).toBe('VoltageOverloaded');
      expect(result.data.finalVoltage).toBe(240);
    }
  });

  it('parses RoomStateSnapshot fixture generated by backend', () => {
    const raw: unknown = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'RoomStateSnapshot.json'), 'utf-8')
    ) as unknown;
    const result = RoomStateSnapshotSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.roomCode).toBe('CYBER-7X9');
      expect(result.data.state).toBe('TurnActive');
      expect(result.data.myHand).toHaveLength(1);
      expect(result.data.myHand[0].protocol).toBe('Alpha');
      expect(result.data.seats).toHaveLength(2);
      expect(result.data.lastTraceResolution?.bluffDetected).toBe(true);
    }
  });

  it('parses TraceResolution fixture generated by backend', () => {
    const raw: unknown = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'TraceResolution.json'), 'utf-8')
    ) as unknown;
    const result = TraceResolutionSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.bluffDetected).toBe(true);
      expect(result.data.declaredProtocol).toBe('Alpha');
      expect(result.data.revealedCards[0].protocol).toBe('Alpha');
    }
  });

  it('parses CardsPlayed fixture generated by backend', () => {
    const raw: unknown = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'CardsPlayed.json'), 'utf-8')
    ) as unknown;
    const result = CardsPlayedEventSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.cardCount).toBe(2);
      expect(result.data.declaredProtocol).toBe('Alpha');
    }
  });

  it('parses PlayerStatusChanged fixture generated by backend', () => {
    const raw: unknown = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'PlayerStatusChanged.json'), 'utf-8')
    ) as unknown;
    const result = PlayerStatusChangedEventSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.status).toBe('Disconnected');
    }
  });

  it('parses RoundStarted fixture generated by backend', () => {
    const raw: unknown = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'RoundStarted.json'), 'utf-8')
    ) as unknown;
    const result = RoundStartedEventSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.roundNumber).toBe(1);
      expect(result.data.leadProtocol).toBe('Alpha');
    }
  });

  it('parses PlayerJoined payload both as direct seat and wrapped event', () => {
    const directSeat = {
      playerId: 'a0000000-0000-4000-8000-000000000001',
      nickname: 'AliceHost',
      status: 'Active',
      isReady: true,
      handCount: 5,
    };
    const directResult = PlayerJoinedEventSchema.safeParse(directSeat);
    expect(directResult.success).toBe(true);

    const wrappedEvent = {
      type: 'PlayerJoined',
      roomCode: 'CYBER-7X9',
      player: directSeat,
    };
    const wrappedResult = PlayerJoinedEventSchema.safeParse(wrappedEvent);
    expect(wrappedResult.success).toBe(true);
  });

  it('fails safely on corrupted payload without throwing', () => {
    const corrupted = {
      type: 'TraceCalled',
      roomCode: 'INVALID',
      callerId: 'not-a-uuid',
    };
    const result = TraceCalledEventSchema.safeParse(corrupted);
    expect(result.success).toBe(false);

    const corruptedSnapshot = {
      roomCode: 'CYBER-7X9',
      state: 'InvalidState',
    };
    const snapshotResult = RoomStateSnapshotSchema.safeParse(corruptedSnapshot);
    expect(snapshotResult.success).toBe(false);

    const corruptedCardsPlayed = {
      playerId: 'not-a-uuid',
      cardCount: 5, // exceeds max 3
      declaredProtocol: 'UnknownProtocol',
    };
    const cardsPlayedResult = CardsPlayedEventSchema.safeParse(corruptedCardsPlayed);
    expect(cardsPlayedResult.success).toBe(false);
  });
});
