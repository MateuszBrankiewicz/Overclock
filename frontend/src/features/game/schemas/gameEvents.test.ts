import { describe, it, expect } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';
import {
  TraceCalledEventSchema,
  TurnStartedEventSchema,
  VoltageOverloadedEventSchema,
} from './gameEvents';

import { fileURLToPath } from 'node:url';

function findFixturesDir(): string {
  let current = path.dirname(fileURLToPath(import.meta.url));
  while (current && current !== path.parse(current).root) {
    const candidate = path.join(current, 'tests', 'contracts', 'signalr');
    if (fs.existsSync(candidate)) {
      return candidate;
    }
    current = path.dirname(current);
  }
  return path.resolve(process.cwd(), '../../tests/contracts/signalr');
}

const FIXTURES_DIR = findFixturesDir();

describe('SignalR Contract Validation (ADR 0004 & ADR 0007)', () => {
  it('parses TraceCalled fixture generated by backend', () => {
    const raw = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'TraceCalled.json'), 'utf-8')
    );
    const result = TraceCalledEventSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.type).toBe('TraceCalled');
      expect(result.data.bluffDetected).toBe(true);
      expect(result.data.revealedCards).toHaveLength(1);
      expect(result.data.revealedCards[0].suit).toBe('overload');
    }
  });

  it('parses TurnStarted fixture generated by backend', () => {
    const raw = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'TurnStarted.json'), 'utf-8')
    );
    const result = TurnStartedEventSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.type).toBe('TurnStarted');
      expect(result.data.currentVoltage).toBe(120);
    }
  });

  it('parses VoltageOverloaded fixture generated by backend', () => {
    const raw = JSON.parse(
      fs.readFileSync(path.join(FIXTURES_DIR, 'VoltageOverloaded.json'), 'utf-8')
    );
    const result = VoltageOverloadedEventSchema.safeParse(raw);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.type).toBe('VoltageOverloaded');
      expect(result.data.finalVoltage).toBe(240);
    }
  });

  it('fails safely on corrupted payload without throwing', () => {
    const corrupted = {
      type: 'TraceCalled',
      roomCode: 'INVALID',
      callerId: 'not-a-uuid',
    };
    const result = TraceCalledEventSchema.safeParse(corrupted);
    expect(result.success).toBe(false);
  });
});
